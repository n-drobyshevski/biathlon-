#!/usr/bin/env bash
# ============================================================================
#  gen-flags.sh — generate a fresh .env with random flags on the Pi.
#  Run once before the event:   ./scripts/gen-flags.sh
#  Re-run to rotate flags (e.g. if they leak during a practice run).
# ============================================================================
set -euo pipefail
cd "$(dirname "$0")/.."

ENV_FILE=".env"

# Create handouts/dist as you now: if docker compose creates it first (it is
# mounted into the hub), it would belong to root and the scripts couldn't
# write there.
mkdir -p handouts/dist

if [[ -f "$ENV_FILE" ]]; then
  read -r -p ".env already exists. Overwrite with NEW flags? [y/N] " ans
  [[ "${ans:-N}" =~ ^[Yy]$ ]] || { echo "Aborted."; exit 0; }
fi

# random lowercase-hex token
tok() { head -c 16 /dev/urandom | od -An -tx1 | tr -d ' \n' | cut -c1-"${1:-12}"; }

# Settings added by hand (CTFd token, host, scoreboard URL) and the CTFd
# secret survive a flag rotation: read them from the old .env first.
keep() { [[ -f "$ENV_FILE" ]] && grep -E "^$1=" "$ENV_FILE" | tail -1 || true; }
KEEP_TOKEN=$(keep CTFD_TOKEN); KEEP_HOST=$(keep CTF_HOST); KEEP_URL=$(keep SCOREBOARD_URL)
KEEP_SECRET=$(keep CTFD_SECRET_KEY)

# Triathlon-themed flag bodies + a random suffix. The bodies are intentionally
# NON-spoiling (they don't reveal any challenge's technique), so even though
# this script is committed, nothing here helps a player solve or submit — the
# submittable flag needs the random suffix, which only exists in .env.
cat > "$ENV_FILE" <<EOF
# Auto-generated by gen-flags.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ)
# Do NOT commit this file.

FLAG_01_STAFF=TRIATHLON{clean_transition_$(tok 10)}
FLAG_02_STEGO=TRIATHLON{cold_water_start_$(tok 10)}
FLAG_03_EXIF=TRIATHLON{aero_position_$(tok 10)}

FLAG_04_IDOR=TRIATHLON{brick_session_$(tok 10)}
FLAG_05_PCAP=TRIATHLON{missed_the_mount_line_$(tok 10)}
FLAG_06_SQLI=TRIATHLON{drafting_penalty_$(tok 10)}
FLAG_07_USB=TRIATHLON{spare_tube_$(tok 10)}

FLAG_08_SAP_ICF=TRIATHLON{anchor_leg_$(tok 10)}
FLAG_09_SAP_USR02=TRIATHLON{photo_finish_$(tok 10)}

# --- Audit complémentaire (missions 10-15) ---
FLAG_10_JWT=TRIATHLON{negative_split_$(tok 10)}
FLAG_11_GIT=TRIATHLON{ghost_runner_$(tok 10)}
FLAG_12_SSTI=TRIATHLON{finisher_medal_$(tok 10)}
FLAG_13_SAP_SHORTCUT=TRIATHLON{race_belt_$(tok 10)}
FLAG_14_SAP_GW=TRIATHLON{open_water_$(tok 10)}
FLAG_15_SAP_ABAP=TRIATHLON{the_wall_$(tok 10)}

SABOTEUR_NAME=viktor_lindqvist

# CTFd session key (kept across rotations)
${KEEP_SECRET:-CTFD_SECRET_KEY=$(tok 32)}

# CTFd admin token for scripts/ctfd-setup.py (CTFd: Settings > Access Tokens)
${KEEP_TOKEN:-# CTFD_TOKEN=ctfd_...}
# Address players use to reach the Pi (used in CTFd descriptions)
${KEEP_HOST:-# CTF_HOST=192.168.8.2}
# Optional: override the scoreboard link shown in the cellule de crise
${KEEP_URL:-# SCOREBOARD_URL=http://192.168.8.2:8000}
EOF

chmod 600 "$ENV_FILE"
echo "Wrote $ENV_FILE with fresh flags (mode 600)."
echo
echo "Next:"
echo "  1) docker compose up -d --build        # start web + SAP challenges"
echo "  2) ./scripts/build-handouts.sh         # build forensics/stego files"
echo "  3) serve handouts/dist/ on the scoreboard or a static file share"
