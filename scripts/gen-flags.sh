#!/usr/bin/env bash
# ============================================================================
#  gen-flags.sh — generate a fresh .env with random flags on the Pi.
#  Run once before the event:   ./scripts/gen-flags.sh
#  Re-run to rotate flags (e.g. if they leak during a practice run).
# ============================================================================
set -euo pipefail
cd "$(dirname "$0")/.."

ENV_FILE=".env"

if [[ -f "$ENV_FILE" ]]; then
  read -r -p ".env already exists. Overwrite with NEW flags? [y/N] " ans
  [[ "${ans:-N}" =~ ^[Yy]$ ]] || { echo "Aborted."; exit 0; }
fi

# random lowercase-hex token
tok() { head -c 16 /dev/urandom | od -An -tx1 | tr -d ' \n' | cut -c1-"${1:-12}"; }

# Biathlon-themed flag bodies + a random suffix. The bodies are intentionally
# NON-spoiling (they don't reveal any challenge's technique), so even though
# this script is committed, nothing here helps a player solve or submit — the
# submittable flag needs the random suffix, which only exists in .env.
cat > "$ENV_FILE" <<EOF
# Auto-generated by gen-flags.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ)
# Do NOT commit this file.

FLAG_01_STAFF=BIATHLON{clean_shooting_$(tok 10)}
FLAG_02_STEGO=BIATHLON{cold_barrel_$(tok 10)}
FLAG_03_EXIF=BIATHLON{prone_position_$(tok 10)}

FLAG_04_IDOR=BIATHLON{standing_stage_$(tok 10)}
FLAG_05_PCAP=BIATHLON{missed_the_last_shot_$(tok 10)}
FLAG_06_SQLI=BIATHLON{penalty_loop_$(tok 10)}
FLAG_07_USB=BIATHLON{spare_round_$(tok 10)}

FLAG_08_SAP_ICF=BIATHLON{anchor_leg_$(tok 10)}
FLAG_09_SAP_USR02=BIATHLON{photo_finish_$(tok 10)}

SABOTEUR_NAME=viktor_lindqvist
EOF

chmod 600 "$ENV_FILE"
echo "Wrote $ENV_FILE with fresh flags (mode 600)."
echo
echo "Next:"
echo "  1) docker compose up -d --build        # start web + SAP challenges"
echo "  2) ./scripts/build-handouts.sh         # build forensics/stego files"
echo "  3) serve handouts/dist/ on the scoreboard or a static file share"
